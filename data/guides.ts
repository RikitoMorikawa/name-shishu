/**
 * 読み物。**一覧だけでは答えられない「どこに頼むか」に答える。**
 * 記事は事実にもとづいて書く。推測は書かない（掲載データと同じ方針）。
 */
export type Guide = {
  slug: string
  title: string
  lead: string
  /** カードに出す短い説明 */
  excerpt: string
  updated: string
  /** 淡い面の色味。写真を使わないので、記事ごとに地の色を変えて見分ける */
  tone: 'a' | 'b' | 'c'
  body: Block[]
  /** よくある質問。**構造化データ（FAQPage）にも載る**ので、答えは事実だけで書く */
  faq?: { q: string; a: string }[]
}

/**
 * 本文の部品。
 * **`p` `ul` `note` `stat` の文中には `{{total}}` のような印を書ける** ―
 * 表示するときに掲載データのいまの数字へ置き換わる（lib/listings.ts の fillStats）。
 * 記事に数字を書き置くと、掲載が増えたときに古い数字が残って誰も気づかない。
 */
export type Block = {
  h?: string
  p?: string
  ul?: string[]
  note?: string
  /** 比較表。1行目が見出し */
  table?: { head: string[]; rows: string[][] }
  /** 掲載データから数えた事実。**この媒体にしかない情報** */
  stat?: { value: string; label: string }[]
  /** 短いまとめ。節の終わりに置く */
  point?: string
}

