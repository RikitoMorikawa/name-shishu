// 住所の切り分け。verify.mjs と export.mjs の両方が使う（hp/001 から 2026-09-29 に移した）。
//
// **都道府県は名前で落とす。**「.+?[都道府県]」で落とすと「京都府京都市」が「京都」で切れて
// 市区が「府京都市」になった（2026-09-27）。

export const PREFS =
  '北海道|青森県|岩手県|宮城県|秋田県|山形県|福島県|茨城県|栃木県|群馬県|埼玉県|千葉県|東京都|神奈川県|新潟県|富山県|石川県|福井県|山梨県|長野県|岐阜県|静岡県|愛知県|三重県|滋賀県|京都府|大阪府|兵庫県|奈良県|和歌山県|鳥取県|島根県|岡山県|広島県|山口県|徳島県|香川県|愛媛県|高知県|福岡県|佐賀県|長崎県|熊本県|大分県|宮崎県|鹿児島県|沖縄県'

// 名前の途中に「市」「町」「村」「区」を含む市区町村。先に当てないと「市川市」が「市」で切れる
const TRICKY =
  '市川市|市原市|四日市市|廿日市市|野々市市|町田市|大町市|十日町市|村上市|東村山市|武蔵村山市|村山市|羽村市|田村市|[西北東]村山郡[^ ]+?町'

const CITY_RE = new RegExp(`^(?:${PREFS})?\\s*(${TRICKY}|[^市区町村]+?郡(?:市貝町|玉村町|[^市区町村]+?[町村])|.+?[市区町村])`)

/** 住所から都道府県を返す（「東京都」の形）。無ければ null */
export const prefOf = (addr) => (String(addr ?? '').match(new RegExp(`(${PREFS})`)) ?? [])[1] ?? null

/** 住所から市区町村を返す。〒と都道府県を落とし、政令市は「市」まで（「京都市」） */
export const cityOf = (addr) => {
  if (!addr) return null
  const s = String(addr).replace(/^\s*〒?\s*\d{3}\s*[-−ー]?\s*\d{4}\s*/, '')
  return (s.match(CITY_RE) ?? [])[1] ?? null
}
